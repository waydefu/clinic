import { fileURLToPath } from 'node:url';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';

const state = vi.hoisted(() => ({
  failure: undefined,
  closeCount: 0,
  writes: new Map(),
  browser: undefined,
  marker: new Error('Synthetic asset failure')
}));

vi.mock('node:fs', () => ({
  mkdirSync: vi.fn(),
  readFileSync: vi.fn((path) => {
    if (state.failure === 'read') throw state.marker;
    if (String(path).endsWith('.metadata.json')) {
      return JSON.stringify({
        maxBytes: 100000,
        clinicHours: 'synthetic-preserved-declaration'
      });
    }
    return Buffer.from('synthetic input bytes; fake-browser tests only');
  }),
  writeFileSync: vi.fn((path, value) => {
    if (state.failure === 'write') throw state.marker;
    state.writes.set(String(path).replaceAll('\\', '/'), Buffer.from(value));
  })
}));

vi.mock('@playwright/test', () => {
  return {
    chromium: {
      launch: vi.fn(async () => {
        if (state.failure === 'launch') throw state.marker;
        const page = {
          goto: vi.fn(async () => {
            if (state.failure === 'goto') throw state.marker;
          }),
          evaluate: vi.fn(async (_trustedCallback, args) => {
            if (state.failure === 'encode') throw state.marker;
            const type =
              state.failure === 'format'
                ? 'image/png'
                : (args.type ?? 'image/webp');
            return {
              dataUrl: `data:${type};base64,${Buffer.from('synthetic encoded bytes').toString('base64')}`,
              width: args.targetWidth ?? 80,
              height: args.height ?? 80,
              discardRatio:
                state.failure === 'crop' &&
                typeof args.targetAspect === 'number'
                  ? 0.9
                  : 0,
              trimmed: { width: 840, height: 882 },
              box: { width: 840, height: 882 }
            };
          })
        };
        const browser = {
          newPage: vi.fn(async () => {
            if (state.failure === 'newPage') throw state.marker;
            return page;
          }),
          close: vi.fn(async () => {
            state.closeCount += 1;
          })
        };
        state.browser = browser;
        return browser;
      })
    }
  };
});

const builders = [
  {
    name: 'brand',
    path: './build-brand-assets.mjs',
    run: () => import('./build-brand-assets.mjs'),
    outputCount: 4
  },
  {
    name: 'clinic',
    path: './build-clinic-assets.mjs',
    run: () => import('./build-clinic-assets.mjs'),
    outputCount: 13
  }
];
let savedArgv;
beforeEach(() => {
  savedArgv = process.argv.slice();
  state.failure = undefined;
  state.closeCount = 0;
  state.writes = new Map();
  state.browser = undefined;
  vi.resetModules();
  vi.spyOn(console, 'log').mockImplementation(() => {});
  vi.spyOn(process.stderr, 'write').mockImplementation(() => true);
});
afterEach(() => {
  process.argv = savedArgv;
  vi.restoreAllMocks();
});

async function run(builder) {
  process.argv[1] = fileURLToPath(new URL(builder.path, import.meta.url));
  await builder.run();
}

for (const builder of builders) {
  describe(`${builder.name} generator owned-browser cleanup`, () => {
    it.each(['newPage', 'goto', 'read', 'encode', 'write'])(
      'closes once and retains a %s failure',
      async (failure) => {
        state.failure = failure;
        await expect(run(builder)).rejects.toBe(state.marker);
        expect(state.browser.close).toHaveBeenCalledTimes(1);
        expect(state.closeCount).toBe(1);
      }
    );

    it('keeps encoding format validation fail-closed and closes', async () => {
      state.failure = 'format';
      await expect(run(builder)).rejects.toThrow(/瀏覽器沒有輸出/);
      expect(state.closeCount).toBe(1);
      expect(state.writes.size).toBe(0);
    });

    it('does not invent cleanup ownership when launch itself fails', async () => {
      state.failure = 'launch';
      await expect(run(builder)).rejects.toBe(state.marker);
      expect(state.browser).toBeUndefined();
      expect(state.closeCount).toBe(0);
    });

    it('keeps successful generated bytes and closes once', async () => {
      await run(builder);
      expect(state.closeCount).toBe(1);
      expect(state.writes.size).toBe(builder.outputCount);
      if (builder.name === 'brand') {
        const metadata = [...state.writes].find(([path]) =>
          path.endsWith('.metadata.json')
        );
        expect(JSON.parse(metadata[1].toString()).clinicHours).toBe(
          'synthetic-preserved-declaration'
        );
      }
    });
  });
}

it('keeps the clinic blind-crop denial and closes its browser', async () => {
  state.failure = 'crop';
  await expect(run(builders[1])).rejects.toThrow(/置中裁切/);
  expect(state.closeCount).toBe(1);
});
