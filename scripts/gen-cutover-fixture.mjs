#!/usr/bin/env node
/**
 * Phase G — Cutover Fixture Generator
 *
 * Generates an anonymised fixture for dry-run import testing.
 * Output: output/evidence/phaseG-cutover-fixture.json (gitignored)
 *
 * Usage:
 *   node scripts/gen-cutover-fixture.mjs [--count 50]
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomUUID } from 'node:crypto';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const EVIDENCE_DIR = join(ROOT, 'output', 'evidence');

function parseArgs() {
  const args = { count: 50 };
  for (let i = 2; i < process.argv.length; i++) {
    if (process.argv[i] === '--count')
      args.count = parseInt(process.argv[++i], 10);
  }
  return args;
}

const { count } = parseArgs();

mkdirSync(EVIDENCE_DIR, { recursive: true });

const practitioners = [
  'prac-001',
  'prac-002',
  'prac-003',
  'prac-004',
  'prac-005'
];
const resources = ['room-a', 'room-b', 'room-c'];
const statuses = ['confirmed', 'completed', 'cancelled', 'no-show'];

function randomDate(start, end) {
  return new Date(
    start.getTime() + Math.random() * (end.getTime() - start.getTime())
  );
}

const events = [];
const base = new Date('2026-01-01T00:00:00Z');
for (let i = 0; i < count; i++) {
  const start = randomDate(base, new Date('2026-12-31T23:59:59Z'));
  const duration = [15, 30, 45, 60][Math.floor(Math.random() * 4)] * 60 * 1000;
  const end = new Date(start.getTime() + duration);

  events.push({
    // Opaque identifiers — no PII
    id: `evt-${randomUUID().slice(0, 8)}`,
    appointmentId: `appt-${randomUUID().slice(0, 8)}`,

    // Time in UTC (Calendar API uses RFC3339)
    start: start.toISOString(),
    end: end.toISOString(),

    // Opaque resource labels (approved in D-009 allowlist)
    practitionerRef:
      practitioners[Math.floor(Math.random() * practitioners.length)],
    resourceRef: resources[Math.floor(Math.random() * resources.length)],

    // Status for reconciliation
    status: statuses[Math.floor(Math.random() * statuses.length)],

    // Synthetic metadata for dry-run only
    synthetic: true,
    generatedAt: new Date().toISOString()
  });
}

const fixture = {
  generatedAt: new Date().toISOString(),
  count: events.length,
  source: 'generated by scripts/gen-cutover-fixture.mjs for Phase G dry-run',
  disclaimer:
    'NO REAL PATIENT DATA. All identifiers are opaque. Times are synthetic.',
  events
};

const outPath = join(EVIDENCE_DIR, 'phaseG-cutover-fixture.json');
writeFileSync(outPath, JSON.stringify(fixture, null, 2));

console.log(
  `Generated ${events.length} synthetic Calendar events → ${outPath}`
);
console.log('Use for Phase G dry-run import. Do not commit.');
